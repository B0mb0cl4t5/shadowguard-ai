"""Write database/migrations/002_real_ai_tools.sql from real_catalog.py.

    python backend/scripts/build_real_catalog_sql.py

Each vendor starts unread: every answer 'unknown' and unverified, which the rubric
scores as risky, until its policy is fetched and read (the drawer's "Fetch the
latest policy" button, or POST /api/v1/vendors/{id}/analyze with {"fetch": true}).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from real_catalog import REAL_APPS, REAL_VENDORS  # noqa: E402
from shadowguard.scoring import VendorPosture, vendor_posture  # noqa: E402

TARGET = ROOT / "database" / "migrations" / "002_real_ai_tools.sql"


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build() -> str:
    unread = vendor_posture(VendorPosture(), verified=False).score
    vendors = ",\n".join(f"    ({q(n)}, {q(w)}, {q(p)}, {unread})" for n, w, p in REAL_VENDORS)
    apps = ",\n".join(
        f"    ((SELECT id FROM vendors WHERE name = {q(v)}), {q(name)}, {q(domain)}, {q(cat)}, TRUE, FALSE)"
        for name, v, domain, cat in REAL_APPS
    )
    return f"""-- Generated by backend/scripts/build_real_catalog_sql.py from real_catalog.py. Do not edit by hand.
-- Adds real AI tools so traffic to them is recognised. Each vendor starts unread
-- (posture {unread}, unverified) until its published policy is fetched and read.
-- Safe to run twice: existing vendors and domains are left as they are.
INSERT INTO vendors (name, website, policy_url, posture_score) VALUES
{vendors}
ON CONFLICT (name) DO NOTHING;

INSERT INTO saas_apps (vendor_id, name, domain, category, is_ai, approved) VALUES
{apps}
ON CONFLICT (domain) DO NOTHING;
"""


if __name__ == "__main__":
    TARGET.write_text(build(), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)}: {len(REAL_VENDORS)} vendors, {len(REAL_APPS)} tools")
